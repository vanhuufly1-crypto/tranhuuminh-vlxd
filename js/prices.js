function getPrice(brand, productName) {
  const b = PRICES[brand];
  if (!b) return null;
  // Try exact match first
  if (b[productName]) return b[productName];
  // Try partial match
  for (const [key, val] of Object.entries(b)) {
    if (productName.includes(key) || key.includes(productName)) {
      return val;
    }
  }
  return null;
}